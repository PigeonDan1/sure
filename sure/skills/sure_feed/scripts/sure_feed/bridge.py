def _docker_image_tag(model_name: str) -> str:
    safe = "".join(char.lower() if char.isalnum() else "-" for char in model_name)
    safe = "-".join(part for part in safe.split("-") if part)
    return f"sure-{safe}:xforge-onboarding"


