def materialize_model_manifest(manifest: dict[str, Any], model_dir: str | Path) -> dict[str, Any]:
    """Materialize an XForge model source into SURE model-local artifacts."""

    manifest = _require_mapping(manifest, "manifest")
    _require_fields(manifest, ("resource_type", "model_name", "task_type", "source"), "model manifest")
    if manifest["resource_type"] != "model":
        raise BridgeError("model materialization requires resource_type='model'")

    source = _require_mapping(manifest["source"], "source")
    _require_fields(source, ("provider", "id"), "model source")
    provider = str(source["provider"])
    model_root = Path(model_dir)
    checkpoints_dir = model_root / "checkpoints"
    runtime_dir = model_root / ".runtime"
    artifacts_dir = model_root / "artifacts"
    checkpoints_dir.mkdir(parents=True, exist_ok=True)
    runtime_dir.mkdir(parents=True, exist_ok=True)
    artifacts_dir.mkdir(parents=True, exist_ok=True)

    if provider != "local":
        raise BridgeError(
            "materialize_model_manifest currently expects a locally collected source. "
            "Run scripts/xforge_collect_model.py first for remote providers."
        )

    source_path = Path(str(source["id"]))
    destination = checkpoints_dir / source_path.name
    local_model_path, materialization = _materialize_model_path(
        source_path,
        destination,
        runtime_dir,
        source,
    )
    weights_manifest = {
        "resource_type": "model",
        "model_name": str(manifest["model_name"]),
        "task_type": str(manifest["task_type"]),
        "source": source,
        "cache_policy": "model_local_first",
        "checkpoint_root": str(checkpoints_dir.resolve()),
        "runtime_root": str(runtime_dir.resolve()),
        "resolved_local_model_path": str(local_model_path),
        **materialization,
        "materialized_at": _utc_now(),
        "fallback": None,
    }
    _write_json(artifacts_dir / "weights_manifest.json", weights_manifest)

    return {
        "resource_type": "model",
        "model_name": str(manifest["model_name"]),
        "local_model_path": str(local_model_path),
        "weights_manifest": str((artifacts_dir / "weights_manifest.json").resolve()),
    }


def load_manifest(path: str | Path) -> dict[str, Any]:
    return _read_json(Path(path))


def write_summary(path: str | Path, summary: dict[str, Any]) -> None:
    _write_json(Path(path), summary)
