def collect_dataset_manifest(manifest: dict[str, Any], raw_root: str | Path) -> dict[str, Any]:
    """Collect a dataset resource into a local raw directory.

    This bridge keeps collection provider-neutral. XForge discovery selects the
    source; this function materializes local sources and records enough metadata
    for later processing. Network providers are intentionally delegated to their
    normal CLIs/libraries by the script entrypoint.
    """

    manifest = _require_mapping(manifest, "manifest")
    _require_fields(manifest, ("resource_type", "dataset_id", "source"), "dataset manifest")
    if manifest["resource_type"] != "dataset":
        raise BridgeError("dataset collection requires resource_type='dataset'")

    source = _require_mapping(manifest["source"], "source")
    _require_fields(source, ("provider", "id"), "dataset source")
    provider = str(source["provider"])
    dataset_id = str(manifest["dataset_id"])
    output_root = Path(raw_root)
    output_root.mkdir(parents=True, exist_ok=True)

    copied_path: str | None = None
    if provider == "local":
        source_path = Path(str(source["id"]))
        destination = output_root / source_path.name
        copied_path = str(_copy_path(source_path, destination))

    summary = {
        "resource_type": "dataset",
        "dataset_id": dataset_id,
        "provider": provider,
        "raw_root": str(output_root.resolve()),
        "copied_path": copied_path,
        "collected_at": _utc_now(),
        "next_step": "scripts/xforge_process_to_sure.py",
    }
    _write_json(output_root / "manifest.json", {**manifest, "collection_summary": summary})
    return summary


def process_dataset_manifest(manifest: dict[str, Any], output_path: str | Path) -> dict[str, Any]:
    """Transform an XForge raw dataset manifest into SURE JSONL."""

    manifest = _require_mapping(manifest, "manifest")
    _require_fields(
        manifest,
        ("resource_type", "dataset_id", "sure_name", "task", "language", "raw_root", "raw_jsonl"),
        "dataset manifest",
    )
    if manifest["resource_type"] != "dataset":
        raise BridgeError("dataset processing requires resource_type='dataset'")

    field_mapping = _require_mapping(manifest.get("field_mapping", {}), "field_mapping")
    _require_fields(field_mapping, ("key", "path", "target"), "field_mapping")

    raw_root = Path(str(manifest["raw_root"])).resolve()
    raw_jsonl = Path(str(manifest["raw_jsonl"]))
    if not raw_jsonl.is_absolute():
        raw_jsonl = raw_root / raw_jsonl
    if not raw_jsonl.exists():
        raise BridgeError(f"raw_jsonl does not exist: {raw_jsonl}")

    output = Path(output_path)
    output.parent.mkdir(parents=True, exist_ok=True)
    samples_written = 0

    with raw_jsonl.open("r", encoding="utf-8") as src, output.open("w", encoding="utf-8") as dst:
        for line_number, line in enumerate(src, 1):
            line = line.strip()
            if not line:
                continue
            try:
                record = json.loads(line)
            except json.JSONDecodeError as exc:
                raise BridgeError(f"invalid JSONL record {line_number} in {raw_jsonl}: {exc}") from exc
            record = _require_mapping(record, f"{raw_jsonl}:{line_number}")

            audio_value = str(_resolve_record_value(record, str(field_mapping["path"])))
            audio_path = Path(audio_value)
            if not audio_path.is_absolute():
                audio_path = raw_root / audio_path
            if not audio_path.exists():
                raise BridgeError(f"audio path does not exist at record {line_number}: {audio_path}")

            sample = {
                "key": str(_resolve_record_value(record, str(field_mapping["key"]))),
                "path": str(audio_path.resolve()),
                "target": str(_resolve_record_value(record, str(field_mapping["target"]))).strip(),
                "task": str(manifest["task"]),
                "language": str(record.get("language", manifest["language"])),
                "dataset": str(manifest["sure_name"]),
            }
            dst.write(json.dumps(sample, ensure_ascii=False) + "\n")
            samples_written += 1

    summary = {
        "resource_type": "dataset",
        "dataset_id": str(manifest["dataset_id"]),
        "sure_name": str(manifest["sure_name"]),
        "jsonl_path": str(output.resolve()),
        "samples_written": samples_written,
        "processed_at": _utc_now(),
    }
    return summary


def process_dataset_manifest_to_oref(
    manifest: dict[str, Any],
    datasets_root: str | Path,
    allow_missing_audio: bool = False,
) -> dict[str, Any]:
    """Transform an XForge raw dataset manifest into a local OREF dataset.

    This intentionally writes the OREF structure currently consumed by
    DatasetManager._convert_oref_jsonl_to_jsonl: audio files under audio/ and
    sample.jsonl records with annotation/attribute fields.
    """

    manifest = _require_mapping(manifest, "manifest")
    _require_fields(
        manifest,
        ("resource_type", "dataset_id", "sure_name", "task", "language", "raw_root", "raw_jsonl"),
        "dataset manifest",
    )
    if manifest["resource_type"] != "dataset":
        raise BridgeError("dataset OREF processing requires resource_type='dataset'")

    field_mapping = _require_mapping(manifest.get("field_mapping", {}), "field_mapping")
    _require_fields(field_mapping, ("key", "path", "target"), "field_mapping")

    dataset_name = str(manifest["sure_name"])
    raw_root = Path(str(manifest["raw_root"])).resolve()
    raw_jsonl = Path(str(manifest["raw_jsonl"]))
    if not raw_jsonl.is_absolute():
        raw_jsonl = raw_root / raw_jsonl
    if not raw_jsonl.exists():
        raise BridgeError(f"raw_jsonl does not exist: {raw_jsonl}")

    dataset_root = Path(datasets_root) / dataset_name
    audio_dir = dataset_root / "audio"
    sample_jsonl = dataset_root / "sample.jsonl"
    audio_dir.mkdir(parents=True, exist_ok=True)

    samples_written = 0
    missing_audio_count = 0
    with raw_jsonl.open("r", encoding="utf-8") as src, sample_jsonl.open("w", encoding="utf-8") as dst:
        for line_number, line in enumerate(src, 1):
            line = line.strip()
            if not line:
                continue
            try:
                record = json.loads(line)
            except json.JSONDecodeError as exc:
                raise BridgeError(f"invalid JSONL record {line_number} in {raw_jsonl}: {exc}") from exc
            record = _require_mapping(record, f"{raw_jsonl}:{line_number}")

            audio_value = str(_resolve_record_value(record, str(field_mapping["path"])))
            source_audio = Path(audio_value)
            if not source_audio.is_absolute():
                source_audio = raw_root / source_audio
            if not source_audio.exists() and not allow_missing_audio:
                raise BridgeError(f"audio path does not exist at record {line_number}: {source_audio}")

            target_audio = audio_dir / source_audio.name
            audio_missing = not source_audio.exists()
            if audio_missing:
                missing_audio_count += 1
            else:
                if target_audio.exists() and target_audio.resolve() != source_audio.resolve():
                    target_audio = audio_dir / f"{_resolve_record_value(record, str(field_mapping['key']))}_{source_audio.name}"
                shutil.copy2(source_audio, target_audio)

            text = str(_resolve_record_value(record, str(field_mapping["target"]))).strip()
            key = str(_resolve_record_value(record, str(field_mapping["key"])))
            sample_rate = record.get("sample_rate") or record.get("sampling_rate") or record.get("sr") or 16000
            duration = record.get("duration") or record.get("duration_ms") or 0
            language = str(record.get("language", manifest["language"]))
            oref_record = {
                "sample_id": key,
                "attribute": {
                    "path": f"audio/{target_audio.name}",
                    "sample_rate": sample_rate,
                    "duration": duration,
                    "language": language,
                    "missing_audio_placeholder": audio_missing,
                    "original_path": audio_value,
                },
                "annotation": [
                    {
                        "transcription": {
                            "text": [text],
                        }
                    }
                ],
                "task": str(manifest["task"]),
                "dataset": dataset_name,
            }
            dst.write(json.dumps(oref_record, ensure_ascii=False) + "\n")
            samples_written += 1

    registry_entry = {
        "config_name": dataset_name,
        "audio_dir": f"{dataset_name}/audio",
        "jsonl_path": f"{dataset_name}/sample.jsonl",
        "task": str(manifest["task"]),
        "language": str(manifest["language"]),
    }
    summary = {
        "resource_type": "dataset",
        "dataset_id": str(manifest["dataset_id"]),
        "sure_name": dataset_name,
        "oref_root": str(dataset_root.resolve()),
        "sample_jsonl": str(sample_jsonl.resolve()),
        "audio_dir": str(audio_dir.resolve()),
        "samples_written": samples_written,
        "missing_audio_count": missing_audio_count,
        "allow_missing_audio": allow_missing_audio,
        "registry_entry": registry_entry,
        "processed_at": _utc_now(),
    }
    _write_json(dataset_root / "oref_summary.json", summary)
    return summary


def write_oref_registry_entry(
    registry_path: str | Path,
    dataset_name: str,
    registry_entry: dict[str, Any],
) -> dict[str, Any]:
    """Add or update a dataset entry in config/oref_datasets.yaml format."""

    try:
        import yaml
    except ImportError as exc:
        raise BridgeError("pyyaml is required to update OREF dataset registry") from exc

    path = Path(registry_path)
    if path.exists():
        data = yaml.safe_load(path.read_text(encoding="utf-8"))
        if not isinstance(data, dict):
            data = {}
    else:
        data = {}
    datasets = data.setdefault("datasets", {})
    if not isinstance(datasets, dict):
        raise BridgeError("OREF registry 'datasets' must be a mapping")
    data.setdefault("fallbacks", {})
    datasets[dataset_name] = dict(registry_entry)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(yaml.safe_dump(data, allow_unicode=True, sort_keys=True), encoding="utf-8")
    return {
        "registry_path": str(path.resolve()),
        "dataset_name": dataset_name,
        "entry": dict(registry_entry),
        "updated_at": _utc_now(),
    }


