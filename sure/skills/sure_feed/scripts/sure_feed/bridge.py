class BridgeError(ValueError):
    """Raised when an XForge-to-SURE bridge manifest is invalid."""


SURE_MODELS_AGENT_CONTRACT = "docs/agents/model_tool_agent/AGENTS.md"


def _utc_now() -> str:
    return datetime.now(timezone.utc).isoformat()


def _require_mapping(value: Any, name: str) -> dict[str, Any]:
    if not isinstance(value, dict):
        raise BridgeError(f"{name} must be a JSON object")
    return value


def _require_fields(data: dict[str, Any], fields: tuple[str, ...], context: str) -> None:
    missing = [field for field in fields if field not in data or data[field] in (None, "")]
    if missing:
        raise BridgeError(f"{context} missing required field(s): {', '.join(missing)}")


def _read_json(path: Path) -> dict[str, Any]:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise BridgeError(f"invalid JSON at {path}: {exc}") from exc
    return _require_mapping(data, str(path))


def _write_json(path: Path, data: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def _write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def _write_text_if_missing(path: Path, text: str, executable: bool = False) -> bool:
    if path.exists():
        return False
    _write_text(path, text)
    if executable:
        path.chmod(path.stat().st_mode | 0o111)
    return True


def _write_generated_text(path: Path, text: str, executable: bool = False) -> bool:
    if path.exists():
        existing = path.read_text(encoding="utf-8", errors="ignore")
        generated_markers = (
            "sure_feed",
            "xforge-onboarding",
            "SURE_XFORGE_STATIC_ONLY=1",
            "Generated by XForge-SURE bridge",
            "package = false",
        )
        if not any(marker in existing for marker in generated_markers):
            return False
    _write_text(path, text)
    if executable:
        path.chmod(path.stat().st_mode | 0o111)
    return True


def _copy_path(source: Path, destination: Path) -> Path:
    if not source.exists():
        raise BridgeError(f"source path does not exist: {source}")
    destination.parent.mkdir(parents=True, exist_ok=True)
    if source.is_dir():
        if destination.exists():
            shutil.rmtree(destination)
        shutil.copytree(source, destination)
    else:
        shutil.copy2(source, destination)
    return destination.resolve()


def _path_is_relative_to(path: Path, parent: Path) -> bool:
    try:
        path.resolve().relative_to(parent.resolve())
    except ValueError:
        return False
    return True


def _materialize_model_path(
    source: Path,
    destination: Path,
    runtime_root: Path,
    source_metadata: dict[str, Any],
) -> tuple[Path, dict[str, Any]]:
    if not source.exists():
        raise BridgeError(f"source path does not exist: {source}")
    destination.parent.mkdir(parents=True, exist_ok=True)

    original_source = source_metadata.get("original_source")
    original_provider = original_source.get("provider") if isinstance(original_source, dict) else None
    source_is_runtime_cache = _path_is_relative_to(source, runtime_root)
    if original_provider in {"modelscope", "huggingface"} and source_is_runtime_cache:
        materialization = {
            "materialization_strategy": f"{original_provider}_runtime_cache",
            "checkpoint_materialized": False,
            "provider_cache_path": str(source.resolve()),
        }
        return source.resolve(), materialization

    local_model_path = _copy_path(source, destination)
    materialization = {
        "materialization_strategy": "copy_from_local_source",
        "checkpoint_materialized": True,
        "provider_cache_path": None,
    }
    return local_model_path, materialization


def _resolve_record_value(record: dict[str, Any], field: str) -> Any:
    value: Any = record
    for part in field.split("."):
        if not isinstance(value, dict) or part not in value:
            raise BridgeError(f"record missing mapped field: {field}")
        value = value[part]
    return value


def _load_optional_json(path: Path) -> dict[str, Any] | None:
    if not path.exists():
        return None
    return _read_json(path)


def _yaml_string(value: Any) -> str:
    return json.dumps("" if value is None else str(value), ensure_ascii=False)


def _path_for_spec(path: str | Path | None, root: Path) -> str | None:
    if path in (None, ""):
        return None
    resolved = Path(str(path)).resolve()
    try:
        relative = resolved.relative_to(root.resolve())
    except ValueError:
        return str(resolved)
    return f"./{relative.as_posix()}"


def _modelscope_model_url(source: dict[str, Any]) -> str:
    if source.get("url"):
        return str(source["url"])
    if source.get("provider") == "modelscope":
        return f"https://modelscope.cn/models/{source['id']}"
    return str(source.get("id") or "")


