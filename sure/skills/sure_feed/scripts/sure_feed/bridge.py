def _default_server_py(task_type: str) -> str:
    tool_name = _default_tool_name(task_type)
    io_contract = _io_contract_for_task(task_type)
    input_field = io_contract["input_field"]
    content_field = io_contract["primary_field"]
    return f'''#!/usr/bin/env python3
"""Minimal MCP-style server scaffold generated by sure_feed."""

from __future__ import annotations

import json
import os
import sys
from typing import Any


class MCPServer:
    def __init__(self) -> None:
        self._initialized = False
        self._model = None
        self._tools = [{{
            "name": "{tool_name}",
            "description": "Run model-local inference",
            "inputSchema": {{
                "type": "object",
                "properties": {{
                    "{input_field}": {{"type": "string"}},
                    "language": {{"type": "string", "default": "auto"}},
                }},
                "required": ["{input_field}"],
            }},
        }}]

    def _load_model(self):
        if self._model is None:
            from model import ModelWrapper

            self._model = ModelWrapper({{"model_path": os.environ.get("MODEL_PATH")}})
        return self._model

    def _handle_request(self, request: dict[str, Any]) -> dict[str, Any] | None:
        method = request.get("method")
        request_id = request.get("id")
        if method == "initialize":
            self._initialized = True
            return {{
                "jsonrpc": "2.0",
                "id": request_id,
                "result": {{
                    "protocolVersion": "2024-11-05",
                    "capabilities": {{"tools": {{}}}},
                    "serverInfo": {{"name": "xforge-sure-model-server", "version": "0.1.0"}},
                }},
            }}
        if method == "notifications/initialized":
            return None
        if method == "tools/list":
            return {{"jsonrpc": "2.0", "id": request_id, "result": {{"tools": self._tools}}}}
        if method == "tools/call":
            params = request.get("params", {{}})
            arguments = params.get("arguments", {{}})
            try:
                result = self._load_model().predict(arguments).to_dict()
                primary = result.get("{content_field}", "")
                content = primary if isinstance(primary, str) else json.dumps(result, ensure_ascii=False)
                return {{
                    "jsonrpc": "2.0",
                    "id": request_id,
                    "result": {{"content": [{{"type": "text", "text": content}}], "raw": result}},
                }}
            except Exception as exc:
                return {{
                    "jsonrpc": "2.0",
                    "id": request_id,
                    "result": {{"content": [{{"type": "text", "text": f"Error: {{exc}}"}}], "isError": True}},
                }}
        return {{"jsonrpc": "2.0", "id": request_id, "error": {{"code": -32601, "message": str(method)}}}}

    def run(self) -> None:
        for line in sys.stdin:
            line = line.strip()
            if not line:
                continue
            try:
                response = self._handle_request(json.loads(line))
            except Exception as exc:
                response = {{"jsonrpc": "2.0", "id": None, "error": {{"code": -32603, "message": str(exc)}}}}
            if response is not None:
                print(json.dumps(response, ensure_ascii=False), flush=True)


if __name__ == "__main__":
    MCPServer().run()
'''


def _default_validate_py() -> str:
    return '''#!/usr/bin/env python3
"""SURE onboarding validation scaffold generated by sure_feed."""

from __future__ import annotations

import json
import os
import sys
from datetime import datetime, timezone
from pathlib import Path


MODEL_DIR = Path(__file__).resolve().parent
ARTIFACTS_DIR = MODEL_DIR / "artifacts"
VALIDATION_LOG = ARTIFACTS_DIR / "validation.log"


def _log(stage: str, status: str, message: str) -> None:
    ARTIFACTS_DIR.mkdir(parents=True, exist_ok=True)
    payload = {
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "stage": stage,
        "status": status,
        "message": message,
    }
    with VALIDATION_LOG.open("a", encoding="utf-8") as handle:
        handle.write(json.dumps(payload, ensure_ascii=True) + "\\n")


def validate_static() -> int:
    required = [
        "model.spec.yaml",
        "config.yaml",
        "model.py",
        "server.py",
        "__init__.py",
        "artifacts/backend_choice.json",
        "artifacts/build_plan.json",
        "artifacts/xforge_sure_handoff.json",
    ]
    missing = [item for item in required if not (MODEL_DIR / item).exists()]
    if missing:
        _log("VALIDATE_SPEC", "failed", "Missing required files: " + ", ".join(missing))
        return 2
    _log("VALIDATE_SPEC", "passed", "Static onboarding files are present.")
    return 0


def main() -> int:
    static_status = validate_static()
    if static_status != 0:
        return static_status
    if os.environ.get("SURE_XFORGE_STATIC_ONLY", "0") == "1":
        return 0

    sys.path.insert(0, str(MODEL_DIR))
    from model import ModelWrapper

    wrapper = ModelWrapper()
    health = wrapper.healthcheck()
    _log("VALIDATE_IMPORT", "passed", "ModelWrapper imported; health=" + json.dumps(health))
    _log("VALIDATE_LOAD", "pending_tool_agent", "Generated scaffold cannot load model-specific weights yet.")
    return 3


if __name__ == "__main__":
    raise SystemExit(main())
'''


